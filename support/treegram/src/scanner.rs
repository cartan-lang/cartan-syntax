//! The grammar's external scanner: the C file, `src/scanner.c`, that
//! tree-sitter compiles beside the generated parser to read the tokens
//! [`crate::print()`] declares as `externals`. Everything it decides is
//! read off the same [`Grammar`] value, and nothing in it is written by
//! hand.
//!
//! **The newline token** ([`Grammar::newline`]). The interpreter reads a
//! newline as a token and states where one may stand; the printed grammar
//! leaves the optional ones out, and the scanner returns the token only
//! where the parser can take it — as a separator — so that every other
//! newline is whitespace. A newline is no separator where the next line
//! opens with a continuation: a token whose pattern carries its own
//! leading newlines, `(\n[ \t\r]*)*` followed by its text, which the
//! interpreter's longest match takes over the separator. The scanner
//! looks past blank lines and indentation for those texts, and for a
//! word continuation the one character after the word its pattern
//! states. A newline before the end of the text separates nothing.
//!
//! **The lookaheads** ([`Grammar::lookaheads`]). Each is a zero-width
//! token the scanner returns where it is valid and its condition holds
//! of the next token, which the scanner reads the way tree-sitter's
//! lexer would: a word, told a keyword or a name; otherwise the longest
//! literal the grammar states; and the first character, for the pattern
//! tokens. What a rule can begin with, and what continues an expression
//! rule after an operand, are the rule's first tokens, computed from the
//! value.
//!
//! In tree-sitter's error recovery every external token is valid at once,
//! which the scanner tells by the error sentinel: it then returns
//! newlines and no lookahead.

use std::collections::{BTreeMap, BTreeSet};

use crate::pattern::{ClassItem, Pat};
use crate::print::{externals, op_text, ERROR_SENTINEL};
use crate::rule::{Body, Climb, Form, Grammar, Holds, Lookahead, Rule};

/// The `src/scanner.c` of a grammar, or nothing where the grammar
/// states neither a newline token nor a lookahead.
pub fn scanner(g: &Grammar) -> Option<String> {
    let externals = externals(g);
    if externals.is_empty() {
        return None;
    }
    let reader = Reader::of(g);
    let mut out = String::new();
    out.push_str(&format!(
        r#"/* The external scanner of the {name} grammar, generated by treegram
 * from the grammar value that also prints grammar.js. Do not edit. */

#include "tree_sitter/parser.h"

"#,
        name = g.name
    ));
    out.push_str("enum TokenType {\n");
    for name in &externals {
        out.push_str(&format!("  {},\n", c_name(name)));
    }
    out.push_str("};\n\n");
    out.push_str(&format!(
        r#"static void skip(TSLexer *lexer) {{ lexer->advance(lexer, true); }}

static void step(TSLexer *lexer) {{ lexer->advance(lexer, false); }}

static bool is_space(int32_t c) {{ return {space}; }}

static bool is_word_start(int32_t c) {{ return {word_start}; }}

static bool is_word_part(int32_t c) {{ return {word_part}; }}

"#,
        space = class_test("c", &reader.space, false),
        word_start = class_test("c", &reader.word_start, false),
        word_part = class_test("c", &reader.word_part, false),
    ));
    out.push_str(&reader.next_token_fns());
    if g.newline.is_some() {
        out.push_str(&reader.continuation_fn());
    }
    if !g.lookaheads.is_empty() {
        let mut sets: Vec<String> = Vec::new();
        for l in &g.lookaheads {
            out.push_str(&reader.holds_fn(l, &mut sets));
        }
    }
    out.push_str(&format!(
        r#"void *tree_sitter_{name}_external_scanner_create(void) {{ return NULL; }}

void tree_sitter_{name}_external_scanner_destroy(void *payload) {{ (void)payload; }}

unsigned tree_sitter_{name}_external_scanner_serialize(void *payload, char *buffer) {{
  (void)payload;
  (void)buffer;
  return 0;
}}

void tree_sitter_{name}_external_scanner_deserialize(void *payload, const char *buffer,
                                                     unsigned length) {{
  (void)payload;
  (void)buffer;
  (void)length;
}}

bool tree_sitter_{name}_external_scanner_scan(void *payload, TSLexer *lexer,
                                              const bool *valid_symbols) {{
  (void)payload;
  bool recovering = valid_symbols[{sentinel}];
  bool spaced = false;
  while (is_space(lexer->lookahead)) {{
    skip(lexer);
    spaced = true;
  }}
"#,
        name = g.name,
        sentinel = c_name(ERROR_SENTINEL),
    ));
    if let Some(newline) = &g.newline {
        out.push_str(&format!(
            r#"  if (valid_symbols[{nl}] && lexer->lookahead == '\n') {{
    step(lexer);
    lexer->mark_end(lexer);
    lexer->result_symbol = {nl};
    while (is_space(lexer->lookahead) || lexer->lookahead == '\n') step(lexer);
    if (lexer->eof(lexer)) return false;
    return !continues_line(lexer);
  }}
"#,
            nl = c_name(newline)
        ));
    }
    if !g.lookaheads.is_empty() {
        let any: Vec<String> = g
            .lookaheads
            .iter()
            .map(|l| format!("valid_symbols[{}]", c_name(&l.name)))
            .collect();
        out.push_str(&format!(
            "  if (recovering || !({})) return false;\n",
            any.join(" || ")
        ));
        out.push_str("  lexer->mark_end(lexer);\n");
        out.push_str("  Next next = next_token(lexer, spaced);\n");
        for l in &g.lookaheads {
            out.push_str(&format!(
                r#"  if (valid_symbols[{t}] && holds_{f}(next)) {{
    lexer->result_symbol = {t};
    return true;
  }}
"#,
                t = c_name(&l.name),
                f = c_ident(&l.name),
            ));
        }
    } else {
        out.push_str("  (void)recovering;\n  (void)spaced;\n");
    }
    out.push_str("  return false;\n}\n");
    Some(out)
}

/// The C enumerator of an external token.
fn c_name(name: &str) -> String {
    c_ident(name).to_uppercase()
}

/// A token's name as a C identifier: its leading underscores dropped.
fn c_ident(name: &str) -> String {
    name.trim_start_matches('_').to_string()
}

/// A C test that the code point in `var` stands in the class.
fn class_test(var: &str, items: &[ClassItem], negated: bool) -> String {
    let terms: Vec<String> = items
        .iter()
        .map(|it| match it {
            ClassItem::Ch(c) => format!("{var} == {}", *c as u32),
            ClassItem::Range(a, b) => format!("({var} >= {} && {var} <= {})", *a as u32, *b as u32),
        })
        .collect();
    let any = if terms.is_empty() {
        "false".to_string()
    } else {
        terms.join(" || ")
    };
    if negated {
        format!("({var} != 0 && !({any}))")
    } else {
        any
    }
}

/// An operator that may open a line: its text, and for a word the
/// characters one of which must follow it.
#[derive(Clone, Debug, PartialEq)]
struct Continuation {
    text: String,
    follow: Option<Vec<ClassItem>>,
}

/// What a rule can begin with, as the scanner reads the next token.
#[derive(Clone, Debug, Default)]
struct Starts {
    /// A name: the grammar's word token.
    word: bool,
    keywords: BTreeSet<String>,
    /// Literal tokens that are no words.
    literals: BTreeSet<String>,
    /// The first characters of the pattern tokens, each a class and
    /// whether it is negated.
    chars: Vec<(Vec<ClassItem>, bool)>,
}

impl Starts {
    fn extend(&mut self, other: Starts) {
        self.word |= other.word;
        self.keywords.extend(other.keywords);
        self.literals.extend(other.literals);
        self.chars.extend(other.chars);
    }
}

/// The grammar as the scanner reads it.
struct Reader<'g> {
    g: &'g Grammar,
    space: Vec<ClassItem>,
    word_start: Vec<ClassItem>,
    word_part: Vec<ClassItem>,
    keywords: Vec<String>,
    /// Every literal token that is no word, numbered from 1 in order.
    literals: Vec<String>,
    continuations: Vec<Continuation>,
    nullable: BTreeMap<String, bool>,
}

impl<'g> Reader<'g> {
    fn of(g: &'g Grammar) -> Reader<'g> {
        let (word_start, word_part) = word_classes(g);
        let mut visible = Vec::new();
        for d in &g.rules {
            match &d.body {
                Body::Rule(r) => visible_rules(r, &mut visible),
                Body::Climb(c) => {
                    visible_rules(&c.primary, &mut visible);
                    for op in &c.ops {
                        visible_rules(op_text(op), &mut visible);
                    }
                }
            }
        }
        let mut space: Vec<ClassItem> = Vec::new();
        let mut continuations: Vec<Continuation> = Vec::new();
        let mut literals: BTreeSet<String> = BTreeSet::new();
        for r in &visible {
            match r {
                Rule::Token(inner) | Rule::Immediate(inner) => match &**inner {
                    Rule::Str(s) => {
                        literals.insert(s.clone());
                    }
                    Rule::Pat(p) => {
                        if let Some((indent, c)) = continuation(p) {
                            space = indent;
                            if !continuations.contains(&c) {
                                continuations.push(c);
                            }
                        }
                    }
                    _ => {}
                },
                Rule::Str(s) => {
                    literals.insert(s.clone());
                }
                Rule::Alias(inner, name)
                    if matches!(**inner, Rule::Token(_) | Rule::Immediate(_))
                        && g.def(name).is_none() =>
                {
                    literals.insert(name.clone());
                }
                _ => {}
            }
        }
        if space.is_empty() {
            space = vec![ClassItem::Ch(' '), ClassItem::Ch('\t'), ClassItem::Ch('\r')];
        }
        let starts_word = |s: &str| s.chars().next().is_some_and(|c| in_class(&word_start, c));
        let literals = literals.into_iter().filter(|s| !starts_word(s)).collect();
        let mut reader = Reader {
            g,
            space,
            word_start,
            word_part,
            keywords: g.keywords(),
            literals,
            continuations,
            nullable: BTreeMap::new(),
        };
        reader.nullable = reader.nullables();
        reader
    }

    /// Whether each named rule matches the empty text, to a fixed point.
    fn nullables(&self) -> BTreeMap<String, bool> {
        let mut out: BTreeMap<String, bool> = BTreeMap::new();
        loop {
            let mut changed = false;
            for d in &self.g.rules {
                let n = match &d.body {
                    Body::Rule(r) => nullable(r, &out),
                    Body::Climb(c) => nullable(&c.primary, &out),
                };
                if n && !out.get(&d.name).copied().unwrap_or(false) {
                    out.insert(d.name.clone(), true);
                    changed = true;
                }
            }
            if !changed {
                return out;
            }
        }
    }

    /// The climb a name is, or the one that builds the operator node it
    /// names.
    fn climb(&self, name: &str) -> Option<(&'g str, &'g Climb)> {
        self.g.rules.iter().find_map(|d| match &d.body {
            Body::Climb(c) if d.name == name || c.ops.iter().any(|o| o.node == name) => {
                Some((d.name.as_str(), c))
            }
            _ => None,
        })
    }

    /// What `r` can begin with, added to `out`, and whether `r` matches
    /// the empty text. `seen` holds the names already read for this set.
    fn first(&self, r: &Rule, out: &mut Starts, seen: &mut BTreeSet<String>) -> bool {
        match r {
            Rule::Blank
            | Rule::NotAhead(_)
            | Rule::NotAheadSoft(_)
            | Rule::Ahead(_)
            | Rule::Refuse(..)
            | Rule::Lookahead(_) => true,
            Rule::Str(s) => {
                self.literal(s, out);
                false
            }
            Rule::Pat(p) => {
                let (classes, empty) = pat_first(p);
                out.chars.extend(classes);
                empty
            }
            Rule::Sym(name) => self.first_of(name, out, seen),
            Rule::Without(ex) => self.first_of(&ex.expr, out, seen),
            Rule::Seq(rs) => {
                for r in rs {
                    if !self.first(r, out, seen) {
                        return false;
                    }
                }
                true
            }
            Rule::Choice(rs) => {
                let mut empty = false;
                for r in rs {
                    empty |= self.first(r, out, seen);
                }
                empty
            }
            Rule::Repeat(r) | Rule::Optional(r) => {
                self.first(r, out, seen);
                true
            }
            Rule::Repeat1(r)
            | Rule::Prec(_, r)
            | Rule::PrecLeft(_, r)
            | Rule::PrecRight(_, r)
            | Rule::PrecDynamic(_, r)
            | Rule::Field(_, r)
            | Rule::Expect(r, _)
            | Rule::Recover(r, _) => self.first(r, out, seen),
            // one token: a literal, or the characters its text opens with
            Rule::Token(r) | Rule::Immediate(r) => match &**r {
                Rule::Str(s) => {
                    self.literal(s, out);
                    false
                }
                r => {
                    let (classes, empty) = chars_first(r);
                    out.chars.extend(classes);
                    empty
                }
            },
            Rule::Alias(r, name) => {
                let is_token = matches!(**r, Rule::Token(_) | Rule::Immediate(_));
                if is_token && self.g.def(name).is_none() {
                    self.literal(name, out);
                    false
                } else {
                    self.first(r, out, seen)
                }
            }
        }
    }

    /// The first tokens of a named rule or operator node.
    fn first_of(&self, name: &str, out: &mut Starts, seen: &mut BTreeSet<String>) -> bool {
        if self.g.word.as_deref() == Some(name) {
            out.word = true;
            return false;
        }
        if self.g.newline.as_deref() == Some(name) {
            return false;
        }
        let empty = self.nullable.get(name).copied().unwrap_or(false);
        if !seen.insert(name.to_string()) {
            return empty;
        }
        match self.g.def(name).map(|d| &d.body) {
            Some(Body::Rule(r)) => self.first(r, out, seen),
            Some(Body::Climb(c)) => self.climb_first(c, out, seen),
            None => {
                let Some((climb, c)) = self.climb(name) else {
                    return false;
                };
                let mut empty = false;
                for op in c.ops.iter().filter(|o| o.node == name) {
                    empty |= match &op.form {
                        Form::Prefix { head, .. } => self.first(head, out, seen),
                        _ => self.first_of(climb, out, seen),
                    };
                }
                empty
            }
        }
    }

    fn climb_first(&self, c: &Climb, out: &mut Starts, seen: &mut BTreeSet<String>) -> bool {
        let mut empty = self.first(&c.primary, out, seen);
        for op in &c.ops {
            if let Form::Prefix { head, .. } = &op.form {
                if prints(head) {
                    empty |= self.first(head, out, seen);
                }
            }
        }
        empty
    }

    /// What continues an operand of the expression rule `name`: the
    /// first tokens of its infix operators and postfix tails, those that
    /// must stand against the operand apart.
    fn continues(&self, name: &str) -> (Starts, Starts) {
        let mut spaced = Starts::default();
        let mut immediate = Starts::default();
        let Some((_, c)) = self.climb(name) else {
            panic!("the lookahead's operand `{name}` is no expression rule");
        };
        for op in &c.ops {
            let text = match &op.form {
                Form::Infix { op, .. } => op,
                Form::Postfix { tail, .. } => tail,
                Form::Prefix { .. } => continue,
            };
            if !prints(text) {
                continue;
            }
            let mut starts = Starts::default();
            self.first(text, &mut starts, &mut BTreeSet::new());
            // a token the operator states immediate continues only where
            // nothing stands between it and the operand
            if starts_immediate(text) {
                immediate.extend(starts);
            } else {
                spaced.extend(starts);
            }
        }
        (spaced, immediate)
    }

    /// A literal token, filed as a keyword or as a literal.
    fn literal(&self, s: &str, out: &mut Starts) {
        if self.keywords.iter().any(|k| k == s) {
            out.keywords.insert(s.to_string());
        } else if s
            .chars()
            .next()
            .is_some_and(|c| in_class(&self.word_start, c))
        {
            // a literal opening with a word character, `f"`, reads as a
            // word to the scanner
            out.word = true;
        } else {
            out.literals.insert(s.to_string());
        }
    }

    /// The token reader: the keyword table, the literal trie and the
    /// function that reads the next token.
    fn next_token_fns(&self) -> String {
        let mut out = String::from(
            r#"typedef struct {
  int32_t first;
  bool spaced;
  bool word;
  int keyword;
  int literal;
} Next;

"#,
        );
        out.push_str("static const char *const KEYWORDS[] = {\n");
        for k in &self.keywords {
            out.push_str(&format!("  \"{k}\",\n"));
        }
        out.push_str("  0,\n};\n\n");
        out.push_str(
            r#"/* The keyword the word is, numbered from 1, or 0 for a name. */
static int keyword(const char *word) {
  for (int i = 0; KEYWORDS[i]; i++) {
    const char *k = KEYWORDS[i];
    int j = 0;
    while (k[j] && k[j] == word[j]) j++;
    if (!k[j] && !word[j]) return i + 1;
  }
  return 0;
}

/* The longest literal at the lexer, numbered from 1, or 0. */
static int literal(TSLexer *lexer) {
  int found = 0;
"#,
        );
        let numbered: Vec<(String, usize)> = self
            .literals
            .iter()
            .enumerate()
            .map(|(i, s)| (s.clone(), i + 1))
            .collect();
        out.push_str(&trie(&numbered, 1, &|id| format!("found = {id};")));
        out.push_str("  return found;\n}\n\n");
        out.push_str(
            r#"/* The keyword the word at the lexer is, numbered from 1, or 0 for a
 * name; the lexer stands after the word. */
static int read_word(TSLexer *lexer) {
  char word[32];
  unsigned n = 0;
  while (is_word_part(lexer->lookahead) || (n == 0 && is_word_start(lexer->lookahead))) {
    if (n < sizeof word - 1) word[n] = (char)lexer->lookahead;
    n++;
    step(lexer);
  }
  if (n >= sizeof word) return 0;
  word[n] = 0;
  return keyword(word);
}

static Next next_token(TSLexer *lexer, bool spaced) {
  Next next = {lexer->lookahead, spaced, false, 0, 0};
  if (is_word_start(lexer->lookahead)) {
    next.word = true;
    next.keyword = read_word(lexer);
  } else {
    next.literal = literal(lexer);
  }
  return next;
}

"#,
        );
        out
    }

    /// The function that tells whether the line at the lexer, after a
    /// newline, opens with a continuation: the token there, read as the
    /// lexer reads it, is one, and a word or an operator whose pattern
    /// states a character after it is followed by that character.
    fn continuation_fn(&self) -> String {
        let mut words = String::new();
        let mut literals = String::new();
        let mut followed = String::new();
        for c in &self.continuations {
            if let Some(k) = self.keywords.iter().position(|k| *k == c.text) {
                let test = match &c.follow {
                    Some(items) => class_test("lexer->lookahead", items, false),
                    None => "true".to_string(),
                };
                words.push_str(&format!("      case {}:\n        return {test};\n", k + 1));
            } else if let Some(l) = self.literals.iter().position(|l| *l == c.text) {
                match &c.follow {
                    Some(items) => {
                        let test = class_test("lexer->lookahead", items, false);
                        followed.push_str(&format!("    case {}:\n      return {test};\n", l + 1));
                    }
                    None => literals.push_str(&format!("    case {}:\n", l + 1)),
                }
            } else {
                panic!("the continuation `{}` is no token of the grammar", c.text);
            }
        }
        let mut out = String::from(
            "/* Whether the line at the lexer opens with an operator that continues\n * the line above. */\nstatic bool continues_line(TSLexer *lexer) {\n",
        );
        out.push_str("  if (is_word_start(lexer->lookahead)) {\n    switch (read_word(lexer)) {\n");
        out.push_str(&words);
        out.push_str("      default:\n        return false;\n    }\n  }\n");
        if !literals.is_empty() || !followed.is_empty() {
            out.push_str("  switch (literal(lexer)) {\n");
            if !literals.is_empty() {
                out.push_str(&literals);
                out.push_str("      return true;\n");
            }
            out.push_str(&followed);
            out.push_str("  }\n");
        }
        out.push_str("  return false;\n}\n\n");
        out
    }

    /// The C test that `next` begins one of `starts`.
    fn starts_test(&self, starts: &Starts, immediate: bool) -> String {
        let mut out = String::new();
        let keyword_ids: Vec<String> = self
            .keywords
            .iter()
            .enumerate()
            .filter(|(_, k)| starts.keywords.contains(*k))
            .map(|(i, _)| format!("    case {}:\n", i + 1))
            .collect();
        let literal_ids: Vec<String> = self
            .literals
            .iter()
            .enumerate()
            .filter(|(_, l)| starts.literals.contains(*l))
            .map(|(i, _)| format!("    case {}:\n", i + 1))
            .collect();
        let (guard, hit) = if immediate {
            ("!next.spaced && ", "!next.spaced")
        } else {
            ("", "true")
        };
        out.push_str("  if (next.word) {\n    switch (next.keyword) {\n");
        out.push_str(&keyword_ids.concat());
        if !keyword_ids.is_empty() {
            out.push_str(&format!("      return {hit};\n"));
        }
        out.push_str(&format!(
            "    case 0:\n      return {guard}{};\n    default:\n      return false;\n    }}\n  }}\n",
            starts.word
        ));
        if !literal_ids.is_empty() {
            out.push_str("  switch (next.literal) {\n");
            out.push_str(&literal_ids.concat());
            out.push_str(&format!("      if ({hit}) return true;\n  }}\n"));
        }
        let chars: Vec<String> = starts
            .chars
            .iter()
            .map(|(items, negated)| class_test("next.first", items, *negated))
            .collect();
        if chars.is_empty() {
            out.push_str("  return false;\n");
        } else {
            out.push_str(&format!(
                "  return {}({});\n",
                guard,
                chars.join(" ||\n         ")
            ));
        }
        out
    }

    /// The test one lookahead makes, with the token sets it reads, each
    /// printed once into `sets`.
    fn holds_fn(&self, l: &Lookahead, sets: &mut Vec<String>) -> String {
        let mut out = String::new();
        let mut set = |name: String, starts: &Starts, immediate: bool, out: &mut String| {
            if !sets.contains(&name) {
                out.push_str(&format!("static bool {name}(Next next) {{\n"));
                out.push_str(&self.starts_test(starts, immediate));
                out.push_str("}\n\n");
                sets.push(name.clone());
            }
            name
        };
        let one_of = |texts: &[String]| -> String {
            let mut terms: Vec<String> = Vec::new();
            for t in texts {
                if let Some(i) = self.keywords.iter().position(|k| k == t) {
                    terms.push(format!("(next.word && next.keyword == {})", i + 1));
                } else if let Some(i) = self.literals.iter().position(|k| k == t) {
                    terms.push(format!("(!next.word && next.literal == {})", i + 1));
                } else {
                    panic!("the lookahead names `{t}`, which is no token of the grammar");
                }
            }
            if terms.is_empty() {
                "false".to_string()
            } else {
                terms.join(" || ")
            }
        };
        let begins =
            |operand: &str,
             out: &mut String,
             set: &mut dyn FnMut(String, &Starts, bool, &mut String) -> String| {
                let mut starts = Starts::default();
                self.first_of(operand, &mut starts, &mut BTreeSet::new());
                set(format!("begins_{}", c_ident(operand)), &starts, false, out)
            };
        let test = match &l.holds {
            Holds::NoOperand { operand, or_before } => {
                let begins = begins(operand, &mut out, &mut set);
                format!("!{begins}(next) || {}", one_of(or_before))
            }
            Holds::Operand { operand, except } => {
                let begins = begins(operand, &mut out, &mut set);
                let (spaced, immediate) = self.continues(operand);
                let cont = set(
                    format!("continues_{}", c_ident(operand)),
                    &spaced,
                    false,
                    &mut out,
                );
                let tight = set(
                    format!("abuts_{}", c_ident(operand)),
                    &immediate,
                    true,
                    &mut out,
                );
                format!(
                    "{begins}(next) && !{cont}(next) && !{tight}(next) && !({})",
                    one_of(except)
                )
            }
        };
        out.push_str(&format!(
            "static bool holds_{}(Next next) {{\n  return {test};\n}}\n\n",
            c_ident(&l.name)
        ));
        out
    }
}

/// Whether an operator's text opens with an immediate token.
fn starts_immediate(r: &Rule) -> bool {
    match r {
        Rule::Immediate(_) => true,
        Rule::Seq(rs) => rs.iter().find(|r| prints(r)).is_some_and(starts_immediate),
        Rule::Field(_, r) | Rule::Alias(r, _) => starts_immediate(r),
        _ => false,
    }
}

/// Whether a rule reaches tree-sitter at all, as the printer prints it.
fn prints(r: &Rule) -> bool {
    match r {
        Rule::NotAhead(_) | Rule::NotAheadSoft(_) | Rule::Ahead(_) | Rule::Refuse(..) => false,
        Rule::Seq(rs) | Rule::Choice(rs) => rs.iter().any(prints),
        Rule::Repeat(r)
        | Rule::Repeat1(r)
        | Rule::Optional(r)
        | Rule::Prec(_, r)
        | Rule::PrecLeft(_, r)
        | Rule::PrecRight(_, r)
        | Rule::PrecDynamic(_, r)
        | Rule::Token(r)
        | Rule::Immediate(r)
        | Rule::Field(_, r)
        | Rule::Alias(r, _)
        | Rule::Expect(r, _)
        | Rule::Recover(r, _) => prints(r),
        _ => true,
    }
}

/// Whether a rule matches the empty text, given the named rules known to.
fn nullable(r: &Rule, named: &BTreeMap<String, bool>) -> bool {
    match r {
        Rule::Blank
        | Rule::Repeat(_)
        | Rule::Optional(_)
        | Rule::NotAhead(_)
        | Rule::NotAheadSoft(_)
        | Rule::Ahead(_)
        | Rule::Refuse(..)
        | Rule::Lookahead(_) => true,
        Rule::Str(s) => s.is_empty(),
        Rule::Pat(p) => pat_first(p).1,
        Rule::Sym(n) => named.get(n).copied().unwrap_or(false),
        Rule::Without(ex) => named.get(&ex.expr).copied().unwrap_or(false),
        Rule::Seq(rs) => rs.iter().all(|r| nullable(r, named)),
        Rule::Choice(rs) => rs.iter().any(|r| nullable(r, named)),
        Rule::Repeat1(r)
        | Rule::Prec(_, r)
        | Rule::PrecLeft(_, r)
        | Rule::PrecRight(_, r)
        | Rule::PrecDynamic(_, r)
        | Rule::Token(r)
        | Rule::Immediate(r)
        | Rule::Field(_, r)
        | Rule::Alias(r, _)
        | Rule::Expect(r, _)
        | Rule::Recover(r, _) => nullable(r, named),
    }
}

/// The classes a pattern's first character stands in, and whether the
/// pattern matches the empty text.
fn pat_first(p: &Pat) -> (Vec<(Vec<ClassItem>, bool)>, bool) {
    match p {
        Pat::Ch(c) => (vec![(vec![ClassItem::Ch(*c)], false)], false),
        // `.` is every character but a newline
        Pat::Any => (vec![(vec![ClassItem::Ch('\n')], true)], false),
        Pat::Class { negated, items } => (vec![(items.clone(), *negated)], false),
        Pat::Seq(ps) => {
            let mut out = Vec::new();
            for p in ps {
                let (first, empty) = pat_first(p);
                out.extend(first);
                if !empty {
                    return (out, false);
                }
            }
            (out, true)
        }
        Pat::Alt(ps) => {
            let mut out = Vec::new();
            let mut empty = false;
            for p in ps {
                let (first, e) = pat_first(p);
                out.extend(first);
                empty |= e;
            }
            (out, empty)
        }
        Pat::Star(p) | Pat::Opt(p) => (pat_first(p).0, true),
        Pat::Plus(p) => pat_first(p),
    }
}

/// The classes the text of a token's body opens with, and whether the
/// body matches the empty text.
fn chars_first(r: &Rule) -> (Vec<(Vec<ClassItem>, bool)>, bool) {
    match r {
        Rule::Str(s) => match s.chars().next() {
            Some(c) => (vec![(vec![ClassItem::Ch(c)], false)], false),
            None => (Vec::new(), true),
        },
        Rule::Pat(p) => pat_first(p),
        Rule::Seq(rs) => {
            let mut out = Vec::new();
            for r in rs {
                let (first, empty) = chars_first(r);
                out.extend(first);
                if !empty {
                    return (out, false);
                }
            }
            (out, true)
        }
        Rule::Choice(rs) => {
            let mut out = Vec::new();
            let mut empty = false;
            for r in rs {
                let (first, e) = chars_first(r);
                out.extend(first);
                empty |= e;
            }
            (out, empty)
        }
        Rule::Repeat(r) | Rule::Optional(r) => (chars_first(r).0, true),
        Rule::Repeat1(r)
        | Rule::Prec(_, r)
        | Rule::PrecLeft(_, r)
        | Rule::PrecRight(_, r)
        | Rule::PrecDynamic(_, r)
        | Rule::Token(r)
        | Rule::Immediate(r)
        | Rule::Field(_, r)
        | Rule::Alias(r, _) => chars_first(r),
        _ => (Vec::new(), true),
    }
}

fn in_class(items: &[ClassItem], c: char) -> bool {
    items.iter().any(|it| match it {
        ClassItem::Ch(x) => *x == c,
        ClassItem::Range(a, b) => *a <= c && c <= *b,
    })
}

/// The word token's first and later characters: its pattern is a class
/// followed by any number of a second class.
fn word_classes(g: &Grammar) -> (Vec<ClassItem>, Vec<ClassItem>) {
    let pat = g.word.as_ref().and_then(|w| match &g.def(w)?.body {
        Body::Rule(Rule::Pat(p)) => Some(p),
        _ => None,
    });
    match pat {
        Some(Pat::Seq(ps)) => match ps.as_slice() {
            [Pat::Class {
                negated: false,
                items: start,
            }, Pat::Star(part)] => match &**part {
                Pat::Class {
                    negated: false,
                    items: part,
                } => (start.clone(), part.clone()),
                _ => panic!("the word token's later characters are no class"),
            },
            _ => panic!("the word token is not a class followed by a repeated class"),
        },
        _ => panic!("a scanner reads words, and the grammar names no word token"),
    }
}

/// Every rule the printer reads, each nested rule visited: the
/// interpreter's lookaheads and refusals are left out.
fn visible_rules<'r>(r: &'r Rule, out: &mut Vec<&'r Rule>) {
    out.push(r);
    match r {
        Rule::NotAhead(_) | Rule::NotAheadSoft(_) | Rule::Ahead(_) | Rule::Refuse(..) => {
            out.pop();
        }
        Rule::Seq(rs) | Rule::Choice(rs) => rs.iter().for_each(|r| visible_rules(r, out)),
        Rule::Repeat(r)
        | Rule::Repeat1(r)
        | Rule::Optional(r)
        | Rule::Prec(_, r)
        | Rule::PrecLeft(_, r)
        | Rule::PrecRight(_, r)
        | Rule::PrecDynamic(_, r)
        | Rule::Field(_, r)
        | Rule::Alias(r, _)
        | Rule::Expect(r, _)
        | Rule::Recover(r, _) => visible_rules(r, out),
        // a token's inside is no token of its own
        Rule::Token(_) | Rule::Immediate(_) => {}
        Rule::Blank
        | Rule::Str(_)
        | Rule::Pat(_)
        | Rule::Sym(_)
        | Rule::Without(_)
        | Rule::Lookahead(_) => {}
    }
}

/// A continuation's text and the indentation its leading newlines
/// take, where `p` is a token that opens with `(\n[...]*)*` or
/// `(\n[...]*)+` followed by literal text and at most one class.
fn continuation(p: &Pat) -> Option<(Vec<ClassItem>, Continuation)> {
    let Pat::Seq(ps) = p else { return None };
    let (lead, rest) = ps.split_first()?;
    let (Pat::Star(one) | Pat::Plus(one)) = lead else {
        return None;
    };
    let Pat::Seq(line) = &**one else { return None };
    let [Pat::Ch('\n'), Pat::Star(indent)] = line.as_slice() else {
        return None;
    };
    let Pat::Class {
        negated: false,
        items: indent,
    } = &**indent
    else {
        return None;
    };
    fn flat<'p>(ps: &'p [Pat], out: &mut Vec<&'p Pat>) {
        for p in ps {
            match p {
                Pat::Seq(inner) => flat(inner, out),
                p => out.push(p),
            }
        }
    }
    let mut items = Vec::new();
    flat(rest, &mut items);
    let rest = items;
    let mut text = String::new();
    let mut follow = None;
    for (i, p) in rest.iter().enumerate() {
        match p {
            Pat::Ch(c) if follow.is_none() => text.push(*c),
            Pat::Class {
                negated: false,
                items,
            } if i + 1 == rest.len() => follow = Some(items.clone()),
            _ => panic!("a continuation token is its text and at most one class after it: {p:?}"),
        }
    }
    Some((indent.clone(), Continuation { text, follow }))
}

/// A token pattern without the leading newlines a continuation carries:
/// nothing where `p` carries none, the rest where it may open on the
/// line it continues, and no pattern where it must open a line of its
/// own, which the operator's plain text already stands for.
pub(crate) fn without_lead(p: &Pat) -> Option<Option<Pat>> {
    continuation(p)?;
    let Pat::Seq(ps) = p else { return None };
    let (lead, rest) = ps.split_first()?;
    Some(match lead {
        Pat::Plus(_) => None,
        _ => Some(Pat::Seq(rest.to_vec())),
    })
}

/// A nested `switch` that steps through the texts one character at a
/// time, stating `at_end(id)` where a text ends — before looking for a
/// longer one.
fn trie(texts: &[(String, usize)], depth: usize, at_end: &dyn Fn(usize) -> String) -> String {
    let pad = "  ".repeat(depth);
    let mut by_first: BTreeMap<char, Vec<(String, usize)>> = BTreeMap::new();
    let mut out = String::new();
    for (text, id) in texts {
        let mut chars = text.chars();
        match chars.next() {
            None => out.push_str(&format!("{pad}{}\n", at_end(*id))),
            Some(c) => by_first
                .entry(c)
                .or_default()
                .push((chars.as_str().to_string(), *id)),
        }
    }
    if by_first.is_empty() {
        return out;
    }
    out.push_str(&format!("{pad}switch (lexer->lookahead) {{\n"));
    for (c, rest) in by_first {
        out.push_str(&format!("{pad}  case {}:\n", c as u32));
        out.push_str(&format!("{pad}    step(lexer);\n"));
        out.push_str(&trie(&rest, depth + 2, at_end));
        out.push_str(&format!("{pad}    break;\n"));
    }
    out.push_str(&format!("{pad}}}\n"));
    out
}
